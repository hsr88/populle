"""Extract PopTotal (people on 1 July) from the UN WPP 2024 bulk CSV.

Run: py scripts/import-wpp.py path/to/WPP2024_TotalPopulationBySex.csv.gz
Source: https://population.un.org/wpp/assets/Excel%20Files/1_Indicator%20(Standard)/CSV_FILES/WPP2024_TotalPopulationBySex.csv.gz
"""
import csv
import gzip
import json
import sys
from decimal import Decimal
from pathlib import Path

regions = {
    "World": ["900"], "Asia": ["935"], "Europe": ["908"], "Africa": ["903"],
    "North America": ["905", "916", "915"], "South America": ["931"],
    "Oceania": ["909"], "IND": ["356"], "VEN": ["862"],
}
ids = {code for codes in regions.values() for code in codes}
values = {}
countries = {}
with gzip.open(sys.argv[1], "rt", encoding="utf-8-sig", newline="") as source:
    for row in csv.DictReader(source):
        code, variant = row["LocID"], row["Variant"].lower()
        iso3 = row["ISO3_code"]
        if iso3:
            countries[iso3] = [code]
        if (code in ids or iso3) and variant in {"medium", "high", "low"}:
            key = (code, variant, int(row["Time"]))
            if key in values:
                raise ValueError(f"Duplicate WPP record {key}")
            values[key] = int(Decimal(row["PopTotal"]) * 1000)

def write_series(locations, declaration, filename):
    lines = ["// Generated by scripts/import-wpp.py. Annual mid-year population in persons.", declaration]
    for location, codes in locations.items():
        lines.append(f"  {json.dumps(location)}: {{")
        for variant in ("medium", "high", "low"):
            start = 1950 if variant == "medium" else 2024
            series = [sum(values[code, variant, year] for code in codes)
                      for year in range(start, 2101)]
            lines.append(f"    {variant}: {json.dumps(series)},")
        lines.append("  },")
    lines.append("};")
    target = Path(__file__).resolve().parents[1] / filename
    target.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))


write_series(regions, "export const annualPopulation = {", "lib/population/src/annualPopulation.ts")
write_series(dict(sorted(countries.items())),
             'export const countrySeries: Record<string, Record<"medium" | "high" | "low", number[]>> = {',
             "artifacts/api-server/src/data/annualCountries.ts")
